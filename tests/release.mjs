import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const base=process.env.PORTFOLIO_TEST_URL||'http://127.0.0.1:3020'
assert.match(base,/^http:\/\/(127\.0\.0\.1|localhost):\d+$/)
const output=process.env.PORTFOLIO_BROWSER_OUTPUT||'/tmp/portfolio-release'
await mkdir(output,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.PORTFOLIO_CHROMIUM_EXECUTABLE})
const report=[]
try {
  const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'})
  const page=await context.newPage()
  await page.goto(base+'/work/rakuten-programmatic-loyalty#explore-model')
  const selects=page.locator('#explore-model select')
  for(const signal of ['settled','fresh','missing']) {
    await selects.nth(0).selectOption(signal)
    await selects.nth(1).selectOption('exhausted')
    assert.match(await page.locator('#explore-model [aria-live]').innerText(),/Hold delivery/)
  }
  await page.getByRole('button',{name:'Reset example'}).click()
  assert.equal(await selects.nth(0).inputValue(),'settled')
  assert.equal(await selects.nth(1).inputValue(),'available')
  await selects.nth(0).focus();await page.keyboard.press('a');await page.keyboard.press('Enter')
  assert.equal(await selects.nth(0).inputValue(),'fresh')
  await page.screenshot({path:output+'/campaign-model-phone.png'})
  await page.goto(base+'/work/rakuten-ai-platform#explore-model')
  await page.getByRole('button',{name:'Unsupported product claim'}).click()
  assert.match(await page.locator('#explore-model [aria-live]').innerText(),/Hold for a qualified reviewer/)
  await page.getByRole('button',{name:'Complete, supported submission'}).click()
  assert.match(await page.locator('#explore-model [aria-live]').innerText(),/has not granted publication authority/)
  report.push('Signature scenarios, budget precedence, reset, keyboard, and human-review boundary')
  await page.goto(base)
  await page.evaluate(()=>document.fonts.ready)
  const font=await page.locator('body').evaluate(el=>getComputedStyle(el).fontFamily)
  assert.match(font,/inter/i)
  const requests=[]
  const fresh=await context.newPage()
  fresh.on('request',r=>{if(r.url().includes('/videos/'))requests.push(r.url())})
  await fresh.goto(base,{waitUntil:'networkidle'})
  assert.equal(requests.length,0,'No video download during initial reduced-motion visit')
  report.push('Local font loaded and initial media downloads deferred')
  await fresh.close()
  await page.route('**/videos/*.mp4',r=>r.abort())
  const video=page.locator('video').first();await video.scrollIntoViewIfNeeded()
  await video.locator('..').getByRole('button',{name:'Play preview',exact:true}).click()
  await video.locator('..').getByRole('status').waitFor()
  assert.match(await video.locator('..').innerText(),/read the product story/)
  report.push('Failed video exposes a readable fallback with retry')
  const noJs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}})
  const staticPage=await noJs.newPage()
  await staticPage.goto(base)
  assert.equal(await staticPage.getByRole('link',{name:'Explore my work',exact:true}).count(),1)
  assert.ok(await staticPage.locator('noscript a').first().isVisible())
  await staticPage.goto(base+'/work/rakuten-programmatic-loyalty')
  assert.match(await staticPage.locator('noscript').innerText(),/Without interactive controls/)
  report.push('Server-rendered identity, work links, video fallback, and static model survive disabled JavaScript')
  await noJs.close()
  const fallback=await browser.newContext({viewport:{width:320,height:568},reducedMotion:'reduce',forcedColors:'active'})
  const degraded=await fallback.newPage()
  await degraded.route('**/*.woff2',r=>r.abort())
  await degraded.route('**/_next/image?*',r=>r.abort())
  await degraded.goto(base,{waitUntil:'networkidle'})
  assert.ok(await degraded.getByRole('heading',{name:'Pranav Deo.',exact:true}).isVisible())
  assert.ok(await degraded.getByRole('link',{name:'Explore my work',exact:true}).isVisible())
  assert.ok(await degraded.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  await degraded.getByRole('button',{name:'Menu',exact:true}).click()
  await degraded.addScriptTag({path:require.resolve('axe-core/axe.min.js')})
  await degraded.screenshot({path:output+'/forced-colors-font-fallback.png'})
  // Axe reads authored colors rather than the forced palette in this browser.
  // Preserve the forced-color screenshot, then scan the normal palette separately.
  await degraded.emulateMedia({forcedColors:'none'})
  const expanded=await degraded.evaluate(()=>window.axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}}))
  await writeFile(output+'/expanded-accessibility.json',JSON.stringify(expanded.violations,null,2))
  assert.deepEqual(expanded.violations.map(v=>v.id),[])
  report.push('Failed font and images preserve identity and layout; forced-color view captured; expanded menu passes automated accessibility in its normal palette')
  await fallback.close()
  await page.unroute('**/videos/*.mp4')
  await page.goto(base+'/#connect')
  await page.route('https://formspree.io/**',r=>r.fulfill({status:503,body:'Service unavailable'}))
  await page.getByLabel('Name',{exact:true}).fill('Local validation')
  await page.getByLabel('Email',{exact:true}).fill('test@example.com')
  await page.getByLabel('What would you like to talk about?').fill('Intercepted local validation. No message is sent.')
  await page.getByRole('button',{name:'Send message',exact:true}).click()
  await page.getByText('I could not confirm delivery.',{exact:false}).waitFor()
  await page.addScriptTag({path:require.resolve('axe-core/axe.min.js')})
  const errorScan=await page.evaluate(()=>window.axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}}))
  assert.deepEqual(errorScan.violations.map(v=>v.id),[])
  await page.screenshot({path:output+'/contact-recovery-phone.png'})
  report.push('Intercepted provider failure preserves message and passes automated accessibility in its error state')
  await context.close()
  await writeFile(output+'/release.json',JSON.stringify({passed:report},null,2))
  report.forEach(item=>console.log('PASS '+item))
} finally {await browser.close()}
